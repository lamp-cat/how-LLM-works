const dynamic = [
  [/^Layer (\d+)$/, (_, n) => `第 ${n} 层`],
  [/^Head (\d+)$/, (_, n) => `注意力头 ${n}`],
  [/^Pair (\d+)$/, (_, n) => `维度对 ${n}`],
  [/^Selected: layer (\d+)$/, (_, n) => `已选：第 ${n} 层`],
  [/^Tokenizing (\d+) words\.\.\.$/, (_, n) => `正在对 ${n} 个词分词…`],
  [/^Fetching (\d+) embeddings from the model\.\.\.$/, (_, n) => `正在从模型读取 ${n} 个词嵌入…`],
  [/^Running PCA on \[(.+)\] matrix\.\.\.$/, (_, shape) => `正在对 [${shape}] 矩阵运行 PCA…`],
  [/^Loading model embeddings.*$/, () => "正在加载模型词嵌入…"],
  [/^(\d+) chars · (\d+) tokens$/, (_, a, b) => `${a} 个字符 · ${b} 个 token`],
  [/^Layer (\d+) \((.+)\)$/, (_, n, type) => `第 ${n} 层（${zh[type] || type}）`],
  [/^Head (\d+) · (.+)$/, (_, n, suffix) => `注意力头 ${n} · ${suffix}`],
  [/^High frequency \(pair (\d+)\)$/, (_, n) => `高频（维度对 ${n}）`],
  [/^Low frequency \(pair (\d+)\)$/, (_, n) => `低频（维度对 ${n}）`],
  [/^Unit-circle rotation for (High|Low) frequency \(pair (\d+)\) at position (\d+)$/, (_, freq, pair, pos) => `位置 ${pos} 的${freq === "High" ? "高频" : "低频"}维度对 ${pair} 的单位圆旋转`],
  [/^▶ Sweep position m$/, () => "▶ 扫描位置 m"],
  [/^(\d+) query heads, (\d+) KV heads$/, (_, q, kv) => `${q} 个 query 头，${kv} 个 KV 头`],
  [/^pair (\d+) · (fast|slow)$/, (_, n, speed) => `维度对 ${n} · ${speed === "fast" ? "快" : "慢"}`],
  [/^Unit-circle rotation for (高频|低频)（维度对 (\d+)） at position (\d+)$/, (_, freq, pair, pos) => `位置 ${pos} 的${freq}维度对 ${pair} 的单位圆旋转`],
];

export function translatePanel(value, locale) {
  if (locale !== "zh") return value;
  if (Array.isArray(value)) return value.map(item => translatePanel(item, locale));
  if (typeof value !== "string") return value;
  if (Object.hasOwn(zh, value)) return zh[value];
  for (const [pattern, format] of dynamic) {
    if (pattern.test(value)) return value.replace(pattern, format);
  }
  return value;
}
